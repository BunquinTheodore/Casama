"""The files the app and the video consume, and that the Dart port is tested against."""

import json
import random
import re
from datetime import datetime, timedelta

import pytest

from export_artifacts import (
    DART_FILES,
    build_demo_presence,
    build_golden,
    dart_constants_text,
    params_to_json,
    write_all,
)
from home_forecast import SLOTS, Observation, Params, forecast, habit

PARAMS = Params(b0=-0.1, b1=0.9, b2=1.3, tau_hours=3.0, half_life_days=14.0, prior_strength=2.0, prior=tuple(0.2 + 0.6 * (i % 24) / 23 for i in range(SLOTS)))
MONDAY = datetime(2026, 3, 2)


def fake_homes(days=70):
    rng = random.Random(5)
    homes = {}
    for name in ("alpha", "beta", "gamma"):
        homes[name] = [
            Observation(MONDAY + timedelta(hours=i), rng.random() < 0.6) for i in range(days * 24)
        ]
    return homes


def test_params_json_has_168_prior_values_in_unit_interval():
    data = params_to_json(PARAMS)
    assert data["slots"] == 168 and len(data["prior"]) == 168
    assert all(0.0 <= v <= 1.0 for v in data["prior"])
    assert data["source"]["licence"] == "CC BY 4.0"
    assert data["eps"] == 1e-6 and data["version"] == 1


def test_golden_expected_values_equal_reference_implementation():
    golden = build_golden(PARAMS)
    def as_params(data):
        return Params(**{k: data[k] for k in ("b0", "b1", "b2", "tau_hours", "half_life_days", "prior_strength")}, prior=tuple(data["prior"]))

    for case in golden["cases"]:
        p = as_params(case.get("params", golden["params"]))
        obs = [Observation(datetime.fromisoformat(t), bool(v)) for t, v in case["observations"]]
        now = datetime.fromisoformat(case["now"])
        slot = (now.replace(minute=0) + timedelta(hours=case["hours_ahead"]))
        assert case["expected_forecast"] == pytest.approx(forecast(obs, now, case["home_now"], case["hours_ahead"], p), abs=1e-15)
        assert case["expected_habit"] == pytest.approx(habit(obs, now, slot.weekday() * 24 + slot.hour, p), abs=1e-15)


def test_golden_covers_edge_cases_by_name():
    names = {c["name"] for c in build_golden(PARAMS)["cases"]}
    for needed in (
        "empty_history",
        "one_observation",
        "sunday_to_monday",
        "dst_day",
        "extreme_habit_low",
        "extreme_habit_high",
        "horizon_168",
        "home_now_false",
        "mid_hour_now",
        "observation_at_now_ignored",
        "recent_vs_old",
        "long_history_decay",
    ):
        assert needed in names
    assert len(names) >= 12
    hourly = {c["name"] for c in build_golden(PARAMS)["hourly_cases"]}
    assert {"toggle_mid_hour", "exactly_30_minutes", "first_event_mid_hour", "empty", "sunday_boundary"} <= hourly


def test_golden_hourly_expected_matches_events_to_hourly():
    from derive_hourly import events_to_hourly

    for case in build_golden(PARAMS)["hourly_cases"]:
        events = [(datetime.fromisoformat(t), bool(v)) for t, v in case["events"]]
        got = [[h.strftime("%Y-%m-%dT%H:%M"), 1 if v else 0] for h, v in events_to_hourly(events, datetime.fromisoformat(case["end"]))]
        assert got == case["expected"], case["name"]


def test_demo_seed_members_have_504_characters_of_zero_or_one():
    seed = build_demo_presence(fake_homes())
    assert seed["label"].startswith("demo filler")
    assert set(seed["members"]) == {"m0", "m1", "m2", "m3"}
    for text in seed["members"].values():
        assert len(text) == 504 and set(text) <= {"0", "1"}
    assert datetime.fromisoformat(seed["start"]).weekday() == 0 and datetime.fromisoformat(seed["start"]).hour == 0


def test_demo_seed_members_are_not_identical_streams():
    texts = list(build_demo_presence(fake_homes())["members"].values())
    assert len(set(texts)) == 4


def test_demo_seed_refuses_homes_without_three_contiguous_weeks():
    with pytest.raises(ValueError):
        build_demo_presence({"short": [Observation(MONDAY + timedelta(hours=i), True) for i in range(24 * 10)]})


def test_dart_constants_equal_json_files(tmp_path):
    homes = fake_homes()
    out = tmp_path / "output"
    dart = tmp_path / "dart"
    write_all(PARAMS, homes, out, dart)
    for json_name, dart_name in DART_FILES.items():
        expected = json.loads((out / json_name).read_text(encoding="utf8"))
        text = (dart / dart_name).read_text(encoding="utf8")
        embedded = re.search(r"r'''(.*)'''", text, re.S).group(1)
        assert json.loads(embedded) == expected
        assert "generated by AI/src/export_artifacts.py" in text


def test_export_is_byte_identical_on_second_run(tmp_path):
    homes = fake_homes()
    write_all(PARAMS, homes, tmp_path / "a", tmp_path / "da")
    write_all(PARAMS, homes, tmp_path / "b", tmp_path / "db")
    for name in ("home_forecast.json", "golden.json", "demo_presence.json"):
        assert (tmp_path / "a" / name).read_bytes() == (tmp_path / "b" / name).read_bytes()


def test_dart_constants_text_survives_dollar_signs_and_quotes():
    text = dart_constants_text("x", {"a": "$b 'c' \"d\""}, "note")
    assert json.loads(re.search(r"r'''(.*)'''", text, re.S).group(1)) == {"a": "$b 'c' \"d\""}
